"""MealKit editor icon generator (needs Pillow and numpy: pip install pillow numpy).

    python tools/make_editor_icon.py   -> engine/res/MealKitEditor.ico (window icon), MealKitEditor.png (default project icon),
                                          and ..\\MealKit-Manager\\src\\Logo.h (the same PNG embedded in the Manager) when that repo is beside the engine

A bowl with an orange cube (3D) in it, drawn by tools/make_suite_icons.py with the rest of the suite (docs/TOOL_DESIGN.md section 5).
"""

import io
import os

from PIL import Image

from make_suite_icons import WORKSPACE, editor, save_ico

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "engine", "res", "MealKitEditor.ico")
OUT_PNG = os.path.join(ROOT, "engine", "res", "MealKitEditor.png")
MANAGER_LOGO = os.path.join(WORKSPACE, "MealKit-Manager", "src", "Logo.h")

LOGO_HEADER = """#pragma once

// The MealKit logo (256 px PNG), the default project icon. Copied from the engine's engine/res/MealKitEditor.png
// (the Manager doesn't read engine files at run time); regenerated by the engine's tools/make_editor_icon.py.
#include <cstddef>

namespace mkmanager {

inline constexpr unsigned char kLogoPng[] = {
"""


def write_manager_logo(png):
    lines = ["    " + " ".join("0x%02X," % b for b in png[i : i + 20]) for i in range(0, len(png), 20)]
    text = LOGO_HEADER + "\n".join(lines) + "\n};\n\n} // namespace mkmanager\n"
    with open(MANAGER_LOGO, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main():
    big = editor()
    save_ico(big, OUT)
    small = big.resize((256, 256), Image.LANCZOS)
    small.save(OUT_PNG)
    print("wrote", OUT, OUT_PNG)
    if os.path.isdir(os.path.dirname(MANAGER_LOGO)):
        buf = io.BytesIO()
        small.save(buf, format="PNG")
        write_manager_logo(buf.getvalue())
        print("wrote", MANAGER_LOGO)


if __name__ == "__main__":
    main()
