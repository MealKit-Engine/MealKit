# Generates the external library table and notices (docs/CODING_MODEL.md "Placing external libraries"). Not written by hand; made from third_party/<lib>/mealkit.txt + LICENSE.
#   powershell -ExecutionPolicy Bypass -File tools\gen_notices.ps1              rewrites the engine's third_party/VERSIONS.txt, THIRD_PARTY_NOTICES.txt
#   powershell -ExecutionPolicy Bypass -File tools\gen_notices.ps1 -Check       only checks that both files match mealkit.txt/LICENSE (check.ps1, exit code 1 if different)
#   powershell -ExecutionPolicy Bypass -File tools\gen_notices.ps1 -Project <folder> -Out <file>
#       notices for the shipping folder: MealKit itself (MIT) + engine libraries in the game exe (inGame yes) + project third_party/ + font licenses in assets/fonts
param(
    [switch]$Check,
    [string]$Project = "",
    [string]$Out = ""
)
$ErrorActionPreference = "Stop"
$engine = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding $false

# SDKs not put in the repo (Valve/Epic/console terms): only listed in the table, notices follow those terms
$sdks = @(
    [ordered]@{ name = "Steamworks SDK"; version = "(not included, see the docs)"; license = "Valve"; usedIn = "engine when present"
        source = "https://partner.steamgames.com/"
        why = "lobbies, friend invites, relay. Valve's terms forbid redistributing it, so it is not in the repository; put it in third_party/steamworks/sdk and CMake picks it up." }
    [ordered]@{ name = "EOS SDK (Epic Online Services)"; version = "(not included, see the docs)"; license = "Epic"; usedIn = "engine when present"
        source = "https://dev.epicgames.com/portal"
        why = "cross-play lobbies and P2P relay. Epic's terms forbid redistributing it, so it is not in the repository; put its SDK folder in third_party/eos/sdk and the portal values in third_party/eos/credentials.txt, then build.bat EOS." }
)
$sdkFolders = @("steamworks", "eos")

# mealkit.txt: "key value" lines (# comments)
function Read-Meta([string]$dir) {
    $meta = [ordered]@{ folder = (Split-Path -Leaf $dir); dir = $dir }
    $file = Join-Path $dir "mealkit.txt"
    if (-not (Test-Path $file)) { return $null }
    foreach ($line in [IO.File]::ReadAllLines($file, $utf8)) {
        if ($line -match '^\s*#' -or $line.Trim() -eq "") { continue }
        if ($line -match '^\s*([A-Za-z][A-Za-z0-9]*)\s+(.*?)\s*$') { $meta[$Matches[1]] = $Matches[2] }
    }
    if (-not $meta.Contains("name")) { $meta["name"] = $meta["folder"] }
    return $meta
}

function Read-Libraries([string]$thirdParty) {
    $list = @()
    if (-not (Test-Path $thirdParty)) { return $list }
    foreach ($d in (Get-ChildItem $thirdParty -Directory | Sort-Object { $_.Name.ToLowerInvariant() })) {
        if ($sdkFolders -contains $d.Name) { continue }
        $meta = Read-Meta $d.FullName
        if ($meta) { $list += $meta }
    }
    return $list
}

function License-Text($meta) {
    $name = if ($meta.Contains("licenseFile")) { $meta["licenseFile"] } else { "LICENSE" }
    $path = Join-Path $meta["dir"] $name
    if (-not (Test-Path $path)) { throw "$($meta['folder']): license file $name not found" }
    return ([IO.File]::ReadAllText($path, $utf8)).Replace("`r`n", "`n").TrimEnd()
}

$rule = "=" * 78
function Notice-Block([string]$title, [string]$text) {
    return "$rule`n$title`n$rule`n$text`n"
}

function Title-Of($meta) {
    $t = "$($meta['name']) $($meta['version'])".Trim()
    if ($meta.Contains("note")) { $t += " ($($meta['note']))" }
    return $t
}

# ---------------------------------------------------------------- Engine VERSIONS.txt
function Build-Versions($libs) {
    $rows = @()
    foreach ($m in $libs) { $rows += , @($m["name"], $m["version"], $m["license"], $m["usedIn"], $m["source"]) }
    foreach ($s in $sdks) { $rows += , @($s.name, $s.version, $s.license, $s.usedIn, $s.source) }
    $head = @("Library", "Version", "License", "Used in", "Source")
    $width = @()
    for ($c = 0; $c -lt 5; $c++) {
        $w = $head[$c].Length
        foreach ($r in $rows) { if ($r[$c].Length -gt $w) { $w = $r[$c].Length } }
        $width += $w
    }
    $fmt = { param($r) (($r[0].PadRight($width[0])), ($r[1].PadRight($width[1])), ($r[2].PadRight($width[2])), ($r[3].PadRight($width[3])), $r[4]) -join "  " }
    $lines = @((& $fmt $head).TrimEnd(), (($width | ForEach-Object { "-" * $_ }) -join "  "))
    foreach ($r in $rows) { $lines += (& $fmt $r).TrimEnd() }
    $lines += ""
    $lines += "Why each library (this file is the canonical external library table; the docs repository links here):"
    foreach ($m in $libs) { $lines += "- $($m['name']): $($m['why'])" }
    foreach ($s in $sdks) { $lines += "- $($s.name): $($s.why)" }
    $lines += ""
    $lines += "Generated by tools\gen_notices.ps1 from third_party/<lib>/mealkit.txt and LICENSE - do not edit by hand."
    $lines += "To add or update a library: copy its sources into third_party/<lib>/ (only the files needed to build, see 'kept'),"
    $lines += "keep its LICENSE, write mealkit.txt (name, version, license, licenseFile, source, usedIn, inGame, kept, why) and run the script."
    $lines += "Shipped games include the notices (the export build merges the engine, game and font notices)."
    return ($lines -join "`n") + "`n"
}

function Build-EngineNotices($libs) {
    $text = "MealKit uses the following third-party software. Their licenses require these notices to be distributed with the game.`n"
    $text += "Steamworks SDK and EOS SDK (when used) are covered by the Steamworks SDK Access Agreement and the Epic Online Services terms and are not reproduced here.`n`n"
    $blocks = @()
    foreach ($m in $libs) { $blocks += Notice-Block (Title-Of $m) (License-Text $m) }
    return $text + ($blocks -join "`n")
}

function Write-Crlf([string]$path, [string]$text) {
    [IO.File]::WriteAllText($path, $text.Replace("`n", "`r`n"), $utf8)
}

function Same-Text([string]$path, [string]$text) {
    if (-not (Test-Path $path)) { return $false }
    return ([IO.File]::ReadAllText($path, $utf8)).Replace("`r`n", "`n") -eq $text
}

$engineLibs = Read-Libraries (Join-Path $engine "third_party")

if ($Project -ne "") {
    # ---------------------------------------------------------------- Shipping folder notices
    if ($Out -eq "") { Write-Error "-Out is required with -Project"; exit 1 }
    $Project = (Resolve-Path $Project).Path.TrimEnd("\")
    $text = "This game is made with MealKit and uses the following software. Their licenses require these notices to be distributed with the game.`n"
    $text += "Steamworks SDK and EOS SDK (when used) are covered by the Steamworks SDK Access Agreement and the Epic Online Services terms and are not reproduced here.`n`n"
    $blocks = @(Notice-Block "MealKit $(([IO.File]::ReadAllText((Join-Path $engine 'VERSION'))).Trim())" (([IO.File]::ReadAllText((Join-Path $engine "LICENSE"), $utf8)).Replace("`r`n", "`n").TrimEnd()))
    foreach ($m in $engineLibs) { if ($m["inGame"] -eq "yes") { $blocks += Notice-Block (Title-Of $m) (License-Text $m) } }
    if ($Project -ine $engine) {
        foreach ($m in (Read-Libraries (Join-Path $Project "third_party"))) { $blocks += Notice-Block (Title-Of $m) (License-Text $m) }
    }
    $fonts = Join-Path $Project "assets\fonts"
    if (Test-Path $fonts) {
        foreach ($f in (Get-ChildItem $fonts -Recurse -File -Filter *.txt | Sort-Object FullName)) {
            $blocks += Notice-Block "Font: $($f.BaseName)" (([IO.File]::ReadAllText($f.FullName, $utf8)).Replace("`r`n", "`n").TrimEnd())
        }
    }
    New-Item -ItemType Directory -Force (Split-Path -Parent ([IO.Path]::GetFullPath($Out))) | Out-Null
    Write-Crlf $Out ($text + ($blocks -join "`n"))
    Write-Host "Notices: $Out ($($blocks.Count) entries)"
    exit 0
}

$versionsPath = Join-Path $engine "third_party\VERSIONS.txt"
$noticesPath = Join-Path $engine "THIRD_PARTY_NOTICES.txt"
$versions = Build-Versions $engineLibs
$notices = Build-EngineNotices $engineLibs
if ($Check) {
    $bad = @()
    if (-not (Same-Text $versionsPath $versions)) { $bad += "third_party\VERSIONS.txt" }
    if (-not (Same-Text $noticesPath $notices)) { $bad += "THIRD_PARTY_NOTICES.txt" }
    if ($bad.Count) {
        Write-Host "Out of date: $($bad -join ', ') - run tools\gen_notices.ps1 (do not edit them by hand)" -ForegroundColor Red
        exit 1
    }
    Write-Host "OK notices: $($engineLibs.Count) libraries"
    exit 0
}
Write-Crlf $versionsPath $versions
Write-Crlf $noticesPath $notices
Write-Host "Wrote third_party\VERSIONS.txt and THIRD_PARTY_NOTICES.txt ($($engineLibs.Count) libraries)"
